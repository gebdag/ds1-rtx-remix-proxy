<#
.SYNOPSIS
    Starts Dark Souls in lookdev mode: vanilla rendering through the system d3d9
    plus the lookdev frame capture (F9 or lookdev.py capture).

.DESCRIPTION
    Writes DATA\rtx_comp\settings\remix-comp-proxy.lookdev.ini from the normal remix-comp-proxy.ini
    with the overrides below, then starts DARKSOULS.exe -lookdev. The proxy only
    reads the lookdev INI when it sees -lookdev, so a normal start (Steam, or the
    exe without the flag) is untouched. The normal INI is only read, never written.

.PARAMETER NoLaunch
    Only (re)write the lookdev INI.
#>
param(
    [string]$GameDir = $(if ($env:DS1_LOOKDEV_GAME_DIR) { $env:DS1_LOOKDEV_GAME_DIR } elseif ($env:DS1_GAME_DIR) { "$env:DS1_GAME_DIR\DATA" } else { throw "Set DS1_GAME_DIR (the game folder) or pass -GameDir" }),
    [switch]$NoLaunch
)
$ErrorActionPreference = 'Stop'

# Remix and everything that only exists for it is off; the scene-shaping
# settings (culling, perf kill switches, FPS unlock, resolution) stay as the
# normal INI has them so both modes draw the same frame.
$overrides = [ordered]@{
    'Remix'       = [ordered]@{ 'Enabled' = '0' }
    # (the proxy also bypasses all draw routing in lookdev mode; these keep the INI honest)
    'FFP'         = [ordered]@{ 'Enabled' = '0'; 'AutoEnable' = '0'; 'SkipPostFX' = '0'; 'SuppressAuxPasses' = '0'; 'ExpandSkinnedUV' = '0' }
    'Skinning'    = [ordered]@{ 'Enabled' = '0' }
    'Lights'      = [ordered]@{ 'Enabled' = '0' }
    'PlayerLight' = [ordered]@{ 'Enabled' = '0' }
    'Sun'         = [ordered]@{ 'Enabled' = '0' }
    'Lookdev'     = [ordered]@{ 'Enabled' = '1' }
}

function Set-IniOverrides([string[]]$lines, $overrides) {
    $out = New-Object System.Collections.Generic.List[string]
    $pending = @{}
    foreach ($s in $overrides.Keys) { $pending[$s] = [ordered]@{} + $overrides[$s] }
    $section = $null

    $flush = {
        param($name)
        if ($name -and $pending.ContainsKey($name)) {
            foreach ($k in $pending[$name].Keys) { $out.Add("$k=$($pending[$name][$k])") }
            $pending.Remove($name)
        }
    }

    foreach ($line in $lines) {
        if ($line -match '^\s*\[(.+?)\]\s*$') {
            & $flush $section
            $section = $Matches[1]
            $out.Add($line)
            continue
        }
        if ($section -and $pending.ContainsKey($section) -and $line -match '^\s*([^;=\s][^=]*?)\s*=') {
            $key = $Matches[1]
            $hit = $pending[$section].Keys | Where-Object { $_ -ieq $key } | Select-Object -First 1
            if ($hit) {
                $out.Add("$hit=$($pending[$section][$hit])")
                $pending[$section].Remove($hit)
                continue
            }
        }
        $out.Add($line)
    }
    & $flush $section
    foreach ($name in @($pending.Keys)) {
        $out.Add('')
        $out.Add("[$name]")
        & $flush $name
    }
    return $out
}

# nv tree: DATA belongs to the live set until ..\deploy.conf.DISABLED is renamed to deploy.conf.
if (-not (Test-Path (Join-Path $PSScriptRoot '..\deploy.conf'))) {
    throw "nv tree: ..\deploy.conf is missing, so DATA still belongs to the live set. Use the live tree's lookdev.ps1, or switch the game to the nv set first."
}

$settings = Join-Path $GameDir 'rtx_comp\settings'
New-Item -ItemType Directory -Force $settings | Out-Null
# A build that has not run yet leaves the normal INI in its old place; the proxy would move it at startup.
$old = Join-Path $GameDir 'remix-comp-proxy.ini'
$src = Join-Path $settings 'remix-comp-proxy.ini'
if ((Test-Path $old) -and -not (Test-Path $src)) { Move-Item $old $src }
$dst = Join-Path $settings 'remix-comp-proxy.lookdev.ini'
if (-not (Test-Path $src)) { throw "Normal INI not found: $src" }

$lines = Get-Content -LiteralPath $src -Encoding UTF8
$result = Set-IniOverrides $lines $overrides
$header = @(
    '; GENERATED by lookdev\lookdev.ps1 from remix-comp-proxy.ini - edits here are overwritten.',
    '; Read by the proxy only when the game is started with -lookdev.',
    ''
)
# UTF-8 without a BOM, like the source (a BOM would hide the first [section] from GetPrivateProfile*)
[System.IO.File]::WriteAllLines($dst, [string[]]($header + $result), (New-Object System.Text.UTF8Encoding($false)))
Write-Host "Wrote $dst"

if ($NoLaunch) { return }

if (Get-Process DARKSOULS -ErrorAction SilentlyContinue) {
    throw 'Dark Souls is already running. Close it first (one instance at a time).'
}
Start-Process -FilePath (Join-Path $GameDir 'DARKSOULS.exe') -ArgumentList '-lookdev' -WorkingDirectory $GameDir
Write-Host 'Started DARKSOULS.exe -lookdev. Press F9 in game (or: python lookdev.py capture) to capture a frame.'
