"""Generate assets/ffx/cutscenes.tsv: every cutscene (remo scene) on disk and the map event that plays it, for F4 > Cutscenes.

A scene's id is area, block and cut: scn180130 is area 18, block 1, cut 30. The map it runs on comes from the event script that plays it
(bank 2002 in the map's emevd), because a script may play a scene named after another map: Firelink plays 180130. Scenes no map script
names run on the map their id says.

Usage: py -3.12 scripts/gen_cutscenes.py
"""
import re
import struct
from collections import defaultdict
from pathlib import Path

from gen_map_lights import AREA_NAMES, DATA

EVENTS = DATA / "event"
SCENES = DATA / "remo" / "taeNew" / "win32"
OUT = Path(__file__).parent.parent / "assets" / "ffx" / "cutscenes.tsv"


def events_of(path):
    """(event id, restarts on rest, [(bank, index, args)]) of a PTDE emevd."""
    d = path.read_bytes()
    _ver, _size, nev, oev, _nin, oin, _a, _b, _c, _d, _npar, _opar, _e, _f, _narg, oarg, _g, _h = struct.unpack_from("<18I", d, 8)
    for i in range(nev):
        eid, count, off, _pc, _po, rest, _pad = struct.unpack_from("<7I", d, oev + i * 28)
        ins = []
        for j in range(count):
            bank, idx, alen, aoff, _p, _lay = struct.unpack_from("<IIIiIi", d, oin + off + j * 24)
            ins.append((bank, idx, d[oarg + aoff:oarg + aoff + alen] if alen and aoff >= 0 else b""))
        yield eid, rest, ins


def main():
    by_scene = defaultdict(list)
    for f in sorted(EVENTS.glob("*.emevd")):
        if not re.match(r"m\d\d_\d\d_00_00$", f.stem):
            continue
        for eid, rest, ins in events_of(f):
            for bank, _idx, args in ins:
                if bank == 2002 and len(args) >= 4:
                    scene = struct.unpack_from("<i", args)[0]
                    if scene > 0:
                        by_scene[scene].append((f.stem, eid, rest))
    lines = ["# scene <TAB> map it runs on <TAB> place <TAB> event that plays it, 0 for none <TAB> 1: from an event that does not restart on rest. "
             "Generated by scripts/gen_cutscenes.py."]
    for p in sorted(SCENES.glob("scn*.tae")):
        scene = int(p.stem[3:])
        calls = by_scene.get(scene, [])
        if calls:
            map_name, event, _rest = calls[0]
        else:
            map_name, event = f"m{scene // 10000:02d}_{scene // 100 % 100:02d}_00_00", 0
        once = 1 if calls and all(rest == 0 for _m, _e, rest in calls) else 0
        lines.append(f"{scene}\t{map_name}\t{AREA_NAMES.get(map_name[:6], map_name[:6])}\t{event}\t{once}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(lines) - 1} scenes, {len(by_scene)} played by map events -> {OUT}")


if __name__ == "__main__":
    main()
