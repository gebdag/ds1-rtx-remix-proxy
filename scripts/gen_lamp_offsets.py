"""Generate assets/lights/<map>.lamps.txt: how far a wall lamp's light stands off its wall.

The lights themselves come from the lamp meshes at runtime (game/mesh_lights in the proxy). A lamp hangs on a wall, and a light
at its middle meets that wall at a grazing angle: only what faces the light gets any, so the grooves between bricks light up and the
bricks stay dark, more so the flatter the wall. The game bakes these lamps, and its lightmap shows the source stood well off the wall:
over 110,000 capture vertices it reads 0.41 within a metre of a lantern, 0.70 at 1.5 to 3 m.

So each lamp's light moves out from the nearest wall, stopping short of whatever is in the way. The offsets depend on the map's
geometry, which the proxy cannot see, hence this table. A lamp missing from it keeps its light at its middle.

    x y z  dx dy dz    (lamp's middle, within 1 m, and the offset)

Needs embreex (pip install embreex).

Usage: py -3.12 scripts/gen_lamp_offsets.py [--map m17_00_00_00] [--texture m17_00_light_01] [--out 1.5] [--deploy]
"""
import argparse
import os
import shutil
import sys

import numpy as np

from gen_sky_meshes import diffuse_name
from map_geometry import Scene, blocks_rays, first, map_pieces, rotation, table_sources

HERE = os.path.dirname(os.path.abspath(__file__))
# As game/mesh_lights.cpp: one lamp's parts lie within this of each other.
PART_ACROSS = 0.8
PART_UP = 2.0
# Further than this from any wall, a lamp is not on one.
WALL_WITHIN = 1.5
# Clear of what stops the light on its way out.
CLEARANCE = 0.3
DIRECTIONS = 32


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--data', default=r'<steam dir>\steamapps\common'
                                      r'\Dark Souls Prepare to Die Edition\DATA\unpacked')
    ap.add_argument('--bbformats', default=r'<other project>\tools')
    ap.add_argument('--map', default='m17_00_00_00')
    ap.add_argument('--texture', default='m17_00_light_01')
    ap.add_argument('--out', type=float, default=1.5, help='metres off the wall')
    ap.add_argument('--deploy', action='store_true', help='also into the game\'s rtx_comp\\lights')
    args = ap.parse_args()
    sys.path.insert(0, args.bbformats)
    from bbformats.flver import read_flver

    tables_dir = os.path.join(HERE, '..', 'assets', 'mesh_tables')
    no_block = table_sources(os.path.join(tables_dir, 'sky_meshes.txt')) | table_sources(os.path.join(tables_dir, 'glass_meshes.txt'))
    area = args.map[1:3]
    tris, lamp_points = [], []
    flvers = {}
    for model, at, rot, scale, _light in map_pieces(os.path.join(args.data, 'map', 'MapStudio', f'{args.map}.msb')):
        path = os.path.join(args.data, 'map', args.map, f'{model}A{area}.flver')
        if not os.path.exists(path):
            continue
        if model not in flvers:
            flvers[model] = read_flver(open(path, 'rb').read())
        flver = flvers[model]
        r = rotation(rot) * scale
        for i, mesh in enumerate(flver.meshes):
            fs = mesh.lod0()
            if fs is None or 'position' not in mesh.vertices:
                continue
            p = np.asarray(first(mesh.vertices['position']), np.float64)[:, :3]
            world = p @ r.T + at
            material = flver.materials[mesh.material_index]
            if diffuse_name(material) == args.texture:
                lamp_points.append(world[np.unique(fs.triangles())])
                continue
            t = fs.triangles()
            t = t[(t < len(p)).all(1)]
            if not len(t) or f'{args.map}/{model}A{area}/mesh{i}/lod0' in no_block or not blocks_rays(str(material.mtd)):
                continue
            tris.append(world[t])
    scene = Scene(np.concatenate(tris))

    # The pieces, each one lamp, as the proxy finds them.
    lamps = []
    for points in lamp_points:
        taken = np.zeros(len(points), bool)
        for i in range(len(points)):
            if taken[i]:
                continue
            d = points - points[i]
            near = ~taken & (np.hypot(d[:, 0], d[:, 2]) < PART_ACROSS) & (np.abs(d[:, 1]) < PART_UP)
            taken |= near
            lamps.append((points[near].min(0) + points[near].max(0)) * 0.5)

    angle = np.arange(DIRECTIONS) * 2.0 * np.pi / DIRECTIONS
    around = np.stack([np.cos(angle), np.zeros(DIRECTIONS), np.sin(angle)], 1)
    lines = [f'# How far the light of a {args.texture} lamp on {args.map} stands off its wall. Generated by scripts/gen_lamp_offsets.py; see there.',
             '# x y z  dx dy dz']
    moved = 0
    distances = []
    for lamp in lamps:
        hit = scene.first_hit(np.tile(lamp, (DIRECTIONS, 1)), around)
        nearest = int(np.argmin(hit))
        if not np.isfinite(hit[nearest]) or hit[nearest] > WALL_WITHIN:
            continue
        # The wall's normal: fit to the hits near the nearest, which a single ray through a lamp's bracket would not give.
        close = np.isfinite(hit) & (hit < hit[nearest] * 1.6)
        toward = (around[close] / hit[close, None]).sum(0)
        outward = -toward / np.linalg.norm(toward)
        free = scene.first_hit(lamp[None], outward[None])[0]
        distance = min(args.out, free - CLEARANCE) if np.isfinite(free) else args.out
        if distance <= 0.0:
            continue
        offset = outward * distance
        lines.append(f'{lamp[0]:.2f} {lamp[1]:.2f} {lamp[2]:.2f}  {offset[0]:.3f} {offset[1]:.3f} {offset[2]:.3f}')
        distances.append(distance)
        moved += 1
    out = os.path.join(HERE, '..', 'assets', 'lights', f'{args.map}.lamps.txt')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    if args.deploy:
        shutil.copy2(out, os.path.join(os.path.dirname(args.data), 'rtx_comp', 'lights', f'{args.map}.lamps.txt'))
    print(f'{len(lamps)} lamps, {moved} moved, offset median {np.median(distances):.2f} m, shortest {min(distances):.2f} m -> {os.path.normpath(out)}')


if __name__ == '__main__':
    main()
