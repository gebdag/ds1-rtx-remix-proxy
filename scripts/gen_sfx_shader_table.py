"""Generates src/shared/common/sfx_shaders.inc: every FRPG_Sfx pixel shader in the
game's unpacked shader archive, keyed by the proxy's shader hash
(ffp_state::hash_shader_bytecode: FNV-1a over [version token .. END token]),
with the class the proxy treats it as.

  python scripts/gen_sfx_shader_table.py

Classes come from the shaders' own math (disassembled with lookdev/analyze.py):
  Sprite       rgb = tex * vcolor (then fog, scatter, exposure), a = tex.a * vcolor.a
  SoftSprite   Sprite, alpha also faded by the scene depth over the per-vertex feather
  LitSprite    normal-mapped lighting * tex * vcolor (smoke); a = tex.a * vcolor.a
  DepthEncode  writes the particle's depth encoded into rgb: no colour of its own
  Distortion   warps a copy of the frame (heat haze, refraction)
  Blur         screen-space depth copy / bright pass / blurs

Each row also carries the shader's colour scale: the factor its fog step
(FRPG_Sfx_Pre2.fxh CalcGetFogCol) puts on tex * vcolor before fog, scattering and
exposure, read from the shader's own instruction (the shaders keep their debug names, so
the disassembly marks it "CalcGetFogCol::inCol"). 1 for shaders without that step.

And whether the shader reads the scene depth (DecodeDepthTexture): only those sprites fade
where they meet geometry; the others (SimpleSpriteType0: a message's runes on the floor)
have hard edges in the game.
"""
import os  # noqa: E402  (ds1paths: the local folders, see paths.example.ini)
import sys  # noqa: E402
sys.path.insert(0, os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)))))
import ds1paths  # noqa: E402

import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "lookdev"))
import analyze  # noqa: E402  (D3DX disassembly)
SHADERS = Path(ds1paths.GAME + r"\DATA\unpacked\shader\FRPG_Sfx")
OUT = ROOT / "src" / "shared" / "common" / "sfx_shaders.inc"

CLASSES = {
    "SimpleSpriteType0": "Sprite", "SimpleSpriteType4": "Sprite", "SimpleSpriteType5": "Sprite",
    "SimpleSpriteType7": "Sprite", "PointSpriteType0": "Sprite", "LineType0": "Sprite", "TracerType0": "Sprite",
    "SimpleSprite_DepthType2": "SoftSprite", "SimpleSprite_DepthType6": "SoftSprite", "SimpleSprite_DepthType8": "SoftSprite",
    # byte-identical to the _Depth variants of the same number
    "SimpleSpriteType2": "SoftSprite", "SimpleSpriteType6": "SoftSprite", "SimpleSpriteType8": "SoftSprite",
    "SimpleSpriteType1": "LitSprite", "SimpleSprite_DepthType3": "LitSprite", "SimpleSpriteType3": "LitSprite",
    "TracerType2": "LitSprite",
    "SimpleSprite_DepthType0": "DepthEncode", "SimpleSprite_DepthType1": "DepthEncode", "SimpleSprite_DepthType4": "DepthEncode",
    "SimpleSprite_DepthType5": "DepthEncode", "SimpleSprite_DepthType7": "DepthEncode",
    "TracerType1": "Distortion", "TracerType3": "Distortion",
    **{f"DistortionType{i}": "Distortion" for i in range(6)},
    **{f"BlurType{i}": "Blur" for i in range(4)},
}


def shader_hash(data):
    words = struct.unpack(f"<{len(data) // 4}I", data[: len(data) // 4 * 4])
    i = 1
    while i < len(words):
        tok = words[i]
        if tok == 0x0000FFFF:
            i += 1
            break
        if tok & 0xFFFF == 0xFFFE:
            i += 1 + ((tok >> 16) & 0x7FFF)
        else:
            i += 1 + ((tok >> 24) & 0x0F)
    h = 2166136261
    for b in data[: i * 4]:
        h = ((h ^ b) * 16777619) & 0xFFFFFFFF
    return h


def colour_scale(data):
    """The constant CalcGetFogCol multiplies the sprite colour by (1 when the shader has no fog step)."""
    text = analyze.disassemble(data)
    defs = {m.group(1): [float(x) for x in m.group(2).split(",")] for m in re.finditer(r"def (c\d+), ([^\n]+)", text)}
    for line in text.splitlines():
        if "CalcGetFogCol::inCol" not in line:
            continue
        # mul dst, a, b with one operand a defined constant (either order)
        m = re.match(r"\s*mul \w+\.\w+, ([^,]+), ([^/]+?)\s*//", line)
        consts = [re.match(r"(c\d+)\.([xyzw])$", op.strip()) for op in (m.groups() if m else ())]
        consts = [c for c in consts if c and c.group(1) in defs]
        if len(consts) == 1:
            return defs[consts[0].group(1)]["xyzw".index(consts[0].group(2))]
        raise SystemExit(f"fog step without a constant colour scale: {line.strip()}")
    return 1.0


rows = []
seen = {}
for f in sorted(SHADERS.glob("FRPG_Sfx_*.fpo")):
    key = f.stem[len("FRPG_Sfx_"):]
    cls = CLASSES.get(key)
    if cls is None:
        raise SystemExit(f"unclassified SFX shader: {f.name}")
    data = f.read_bytes()
    h = shader_hash(data)
    if h in seen:
        if seen[h] != cls:
            raise SystemExit(f"{f.name} shares a hash with a shader of class {seen[h]}")
        continue
    seen[h] = cls
    rows.append((h, cls, colour_scale(data), "DecodeDepthTexture" in analyze.disassemble(data), f.stem))

with open(OUT, "w", newline="\n") as out:
    out.write("// GENERATED by scripts/gen_sfx_shader_table.py from the game's FRPG_Sfx pixel shaders.\n")
    out.write("// { proxy shader hash, sfx_class, colour scale before fog, reads the scene depth, name }\n")
    for h, cls, scale, depth, name in rows:
        out.write(f"{{ 0x{h:08X}, sfx_class::{cls}, {scale!r}f, {'true' if depth else 'false'}, \"{name}\" }},\n")
print(f"{len(rows)} SFX pixel shaders -> {OUT}")
