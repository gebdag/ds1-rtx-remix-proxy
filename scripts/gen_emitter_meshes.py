"""Generate assets/mesh_tables/emitter_meshes.txt: character meshes the proxy gives a faint light of their own.

The crystal lizard (chr/c3300) carries a glowing gem, but the game gives it no light. The proxy recognises its
meshes by the hash of the index range it draws, as for the sky meshes (scripts/gen_sky_meshes.py), and game/effect_lights
stands a light in for them. Each mesh contributes one line per face set:
  <FNV-1a 64 of the u16 index bytes, hex> <index count> <model>/mesh<i>/lod<j> <texture>

Usage: py -3.12 scripts/gen_emitter_meshes.py [--data <DATA\\unpacked>] [--bbformats <dir with bbformats>]
"""
import os  # noqa: E402  (ds1paths: the local folders, see paths.example.ini)
import sys  # noqa: E402
sys.path.insert(0, os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)))))
import ds1paths  # noqa: E402

import argparse
import os
import sys

import numpy as np

from gen_sky_meshes import diffuse_name, fnv1a64

MODELS = ('c3300',)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser()
    ap.add_argument('--data', default=ds1paths.GAME + r'\DATA\unpacked')
    ap.add_argument('--bbformats', default=ds1paths.SCRIPTS)
    ap.add_argument('--out', default=os.path.join(here, '..', 'assets', 'mesh_tables', 'emitter_meshes.txt'))
    args = ap.parse_args()

    sys.path.insert(0, args.bbformats)
    from bbformats.flver import read_flver

    lines = []
    for model in MODELS:
        flver = read_flver(open(os.path.join(args.data, 'chr', model, f'{model}.flver'), 'rb').read())
        for i, mesh in enumerate(flver.meshes):
            name = diffuse_name(flver.materials[mesh.material_index])
            for j, fs in enumerate(mesh.face_sets):
                idx = np.asarray(fs.indices, dtype='<u2')
                lines.append(f'{fnv1a64(idx.tobytes()):016x} {len(idx)} {model}/mesh{i}/lod{j} {name}')
    with open(args.out, 'w', newline='\n') as f:
        f.write('# Dark Souls character meshes with a light of their own: <index FNV-1a 64> <index count> <source> <diffuse>\n')
        f.write('# Generated by scripts/gen_emitter_meshes.py; do not edit by hand.\n')
        f.writelines(line + '\n' for line in lines)
    print(len(lines), 'face sets')


if __name__ == '__main__':
    main()
