"""Generate the proxy's FFX effect tables from the effect analysis.

  assets/ffx/ffx_names.tsv   id <TAB> name, every shipped FFX (analysis/ffx_catalogue.csv)
  assets/ffx/ffx_lights.tsv  the lights for effects the game draws without one
                             (analysis/unlit_effect_lights.csv, rows with light = yes)

ffx_lights.tsv columns: id, r, g, b (game units, the light node convention colour x alpha x 2.55),
dwindle begin, dwindle end (m), planar (1 = the dominant sprite lies in the effect's own plane),
persistent (1 = lasts while its map, object, owner or status lasts), confidence (h/m/l),
visual life (s, how long its brightest sprites last), impact (1 = a projectile's hit effect, Bullet.sfxId_Hit, which plays
once: its visual life is that of the sprite the light was measured from, not of its longest sparkle), fade life (s) and fade
(12 comma-separated samples, peak 1): what that sprite gives off over its life, from the effect's own colour and size curves,
category.

usage: python scripts/gen_ffx_tables.py [analysis_dir]
"""
import csv
import pathlib
import re
import sys

ANALYSIS = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else
                        r"<workspace>\Vibe-Reverse-Engineering\patches\DarkSouls\analysis")
OUT = pathlib.Path(__file__).resolve().parent.parent / "assets" / "ffx"

PERSISTENT = ("map-placed", "character idle/aura", "status visual", "world object")


def rows(name):
    with open(ANALYSIS / name, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


# Lights set by hand: r, g, b, dwindle end.
# 90020, the DLC's blue bonfires: a bonfire's reach, at twice a bonfire's peak in the effect's tint (0.2, 0.39, 1);
# the analysis' 0.64 to 2.42 m hardly shows in blue. These used to be a second light that followed the flame draws,
# but the game culls each bonfire's flames by the view (frame_20261101_135358: on screen 38 draws, off screen 0-26),
# so it popped as the camera turned. The table lights every instance whatever is drawn.
OVERRIDES = {"90020": ((0.3, 0.6, 1.5), 4.8)}


def main():
    OUT.mkdir(parents=True, exist_ok=True)

    names = ["# FFX id <TAB> name. Generated from Vibe-Reverse-Engineering/patches/DarkSouls/analysis/ffx_catalogue.csv"]
    names += [f"{r['ffx_id']}\t{r['name']}" for r in rows("ffx_catalogue.csv")]
    (OUT / "ffx_names.tsv").write_text("\n".join(names) + "\n", encoding="utf-8", newline="\n")

    lights = ["# FFX id <TAB> r <TAB> g <TAB> b <TAB> dwindle begin <TAB> dwindle end <TAB> planar <TAB> persistent <TAB> "
              "confidence <TAB> visual life <TAB> impact <TAB> fade life <TAB> fade <TAB> category. Generated by scripts/gen_ffx_tables.py from "
              "Vibe-Reverse-Engineering/patches/DarkSouls/analysis/unlit_effect_lights.csv"]
    count = 0
    sources = {r["ffx_id"]: r["source"] for r in rows("ffx_catalogue.csv")}
    for r in rows("unlit_effect_lights.csv"):
        if r["light"] != "yes":
            continue
        rgb = "\t".join(f"{float(v):.4g}" for v in r["rgb"].split())
        end = float(r["dwindle_end"])
        if r["ffx_id"] in OVERRIDES:
            colour, end = OVERRIDES[r["ffx_id"]]
            rgb = "\t".join(f"{v:.4g}" for v in colour)
        planar = int(r["dominant_sprite"].endswith(":planar"))
        persistent = int(r["lifetime"].startswith(PERSISTENT))
        life = float(r["emissive_life_s"])
        dominant = re.search(r"life([\d.]+)", r["dominant_sprite"])
        impact = int(not persistent and "sfxId_Hit" in sources.get(r["ffx_id"], "") and dominant is not None)
        if impact:
            life = float(dominant.group(1))
        fade = ",".join(r["fade_curve"].split())
        lights.append(f"{r['ffx_id']}\t{rgb}\t{float(r['dwindle_begin']):.4g}\t{end:.4g}\t"
                      f"{planar}\t{persistent}\t{r['confidence'][0]}\t{life:.4g}\t{impact}\t"
                      f"{float(r['fade_life']):.4g}\t{fade}\t{r['category']}")
        count += 1
    (OUT / "ffx_lights.tsv").write_text("\n".join(lights) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(names) - 1} names, {count} lights -> {OUT}")


if __name__ == "__main__":
    main()
