"""Generate the proxy's FFX effect tables from the effect analysis.

  assets/ffx/ffx_names.tsv   id <TAB> name, every shipped FFX (analysis/ffx_catalogue.csv)
  assets/ffx/ffx_lights.tsv  the lights for effects the game draws without one
                             (analysis/unlit_effect_lights.csv, rows with light = yes)

ffx_lights.tsv columns: id, r, g, b (game units, the light node convention colour x alpha x 2.55),
dwindle begin, dwindle end (m), planar (1 = the dominant sprite lies in the effect's own plane),
persistent (1 = lasts while its map, object, owner or status lasts), confidence (h/m/l), category.

usage: python scripts/gen_ffx_tables.py [analysis_dir]
"""
import csv
import pathlib
import sys

ANALYSIS = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else
                        r"<workspace>\Vibe-Reverse-Engineering\patches\DarkSouls\analysis")
OUT = pathlib.Path(__file__).resolve().parent.parent / "assets" / "ffx"

PERSISTENT = ("map-placed", "character idle/aura", "status visual", "world object")


def rows(name):
    with open(ANALYSIS / name, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def main():
    OUT.mkdir(parents=True, exist_ok=True)

    names = ["# FFX id <TAB> name. Generated from Vibe-Reverse-Engineering/patches/DarkSouls/analysis/ffx_catalogue.csv"]
    names += [f"{r['ffx_id']}\t{r['name']}" for r in rows("ffx_catalogue.csv")]
    (OUT / "ffx_names.tsv").write_text("\n".join(names) + "\n", encoding="utf-8", newline="\n")

    lights = ["# FFX id <TAB> r <TAB> g <TAB> b <TAB> dwindle begin <TAB> dwindle end <TAB> planar <TAB> persistent <TAB> "
              "confidence <TAB> category. Generated by scripts/gen_ffx_tables.py from "
              "Vibe-Reverse-Engineering/patches/DarkSouls/analysis/unlit_effect_lights.csv"]
    count = 0
    for r in rows("unlit_effect_lights.csv"):
        if r["light"] != "yes":
            continue
        rgb = "\t".join(f"{float(v):.4g}" for v in r["rgb"].split())
        planar = int(r["dominant_sprite"].endswith(":planar"))
        persistent = int(r["lifetime"].startswith(PERSISTENT))
        lights.append(f"{r['ffx_id']}\t{rgb}\t{float(r['dwindle_begin']):.4g}\t{float(r['dwindle_end']):.4g}\t"
                      f"{planar}\t{persistent}\t{r['confidence'][0]}\t{r['category']}")
        count += 1
    (OUT / "ffx_lights.tsv").write_text("\n".join(lights) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(names) - 1} names, {count} lights -> {OUT}")


if __name__ == "__main__":
    main()
