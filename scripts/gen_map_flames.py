"""Generate assets/ffx/map_flames.tsv: where each map places a flame effect, from its MSB's SFX events.

A map light standing on one of these is that flame's light. The game may hand it to characters only, with its glow on the walls baked
into the lightmap, and it is a torch in Remix all the same (game_lights::characters_only). Every MSB Light is either within 0.5 m of a
flame or more than 6 m from any, so the match leaves no doubt.

Usage: py -3.12 scripts/gen_map_flames.py
"""
from pathlib import Path

from gen_map_lights import EXTRA_FFX, FLAME_FFX, MSB_DIR, read_events

OUT = Path(__file__).parent.parent / "assets" / "ffx" / "map_flames.tsv"


def main():
    # And every effect the catalogue calls a map flame or lantern (Oolacile's fireplace, 120056).
    table = Path(__file__).parent.parent / "assets" / "ffx" / "ffx_lights.tsv"
    catalogued = {int(l.split("\t")[0]) for l in table.read_text(encoding="utf-8").splitlines()
                  if not l.startswith("#") and l.rstrip().endswith("map ambient flame/lantern")}
    wanted = set(FLAME_FFX) | set(EXTRA_FFX) | catalogued
    lines = ["# map <TAB> FFX id <TAB> x <TAB> y <TAB> z. Generated by scripts/gen_map_flames.py from the maps' MSB files."]
    for msb in sorted(MSB_DIR.glob("*.msb")):
        sfx, _lights = read_events(msb)
        lines += [f"{msb.stem}\t{ffx}\t{p[0]:.3f}\t{p[1]:.3f}\t{p[2]:.3f}" for _name, ffx, p in sfx if ffx in wanted]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(lines) - 1} flames -> {OUT}")


if __name__ == "__main__":
    main()
