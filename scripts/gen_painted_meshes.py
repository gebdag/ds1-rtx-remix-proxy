"""Generates assets/mesh_tables/painted_meshes.txt: the Ash Lake meshes whose vertex colour is shade the artists painted.

The lake bed, the beaches and the trunks standing in the water fade to black towards the bottom by grey vertex colour.
Remix's vertexColorIsBakedLighting divides a colour by its largest channel, which turns any grey into white, so the bed
stayed bright sand and the water looked clear. The table names the meshes that keep their colour (Surface::isDs1PaintedColour).

Picked from the game's files: a mesh with vertices under the water plane whose colour there averages below 0.9, plus the
beach meshes that join them (same textures), so no seam shows between tagged and untagged sand. Blended mist is left alone.

Run: python scripts/gen_painted_meshes.py
"""
import glob
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, r"<workspace>\Vibe-Reverse-Engineering\pbr_tools")
import build_pbr as br  # noqa: E402

sys.path.insert(0, str(br.BBFORMATS))
from bbformats.flver import read_flver  # noqa: E402

WATER_PLANE = -322.4  # m0120B2A13, the lake's water mesh
# floor_70 too: the sand strips that run through the beaches, drawn with grey colour like the rest (left out, they stood out as bright polygons).
BEACH = {"m13_n_floor_12", "m13_n_floor_14", "m13_n_floor_70"}
OUT = Path(__file__).parent.parent / "assets" / "mesh_tables" / "painted_meshes.txt"


def fnv1a64(data):
    h = 0xCBF29CE484222325
    for c in data:
        h = ((h ^ c) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


# A face set in another table keeps that table's meaning (the loader keeps the first entry for a hash).
TAKEN = set()
for table in OUT.parent.glob("*.txt"):
    if table != OUT:
        TAKEN |= {line.split()[0] for line in table.read_text(encoding="utf-8").splitlines() if line and line[0] != "#"}

lines = ["# Ash Lake meshes whose vertex colour is painted shade (Surface::isDs1PaintedColour). Generated by scripts/gen_painted_meshes.py: <index FNV-1a 64> <index count> <source>"]
for path in sorted(glob.glob(str(br.GAME_UNPACKED / "map" / "m13_02_00_00" / "*.flver"))):
    flver = read_flver(Path(path).read_bytes(), decode_vertices=True)
    model = Path(path).stem
    for i, mesh in enumerate(flver.meshes):
        material = flver.materials[mesh.material_index]
        mtd = br._stem(material.mtd).lower()
        texture = next((br._stem(t.path) for t in material.textures if t.path and t.type.lower() == "g_diffuse"), None)
        if "fog" in mtd or "water" in mtd or "color" not in mesh.vertices:
            continue
        pos = np.asarray(mesh.vertices["position"], float)
        col = np.asarray(mesh.vertices["color"], float)
        col = (col[0] if col.ndim == 3 else col) / (255.0 if np.max(col) > 1.5 else 1.0)
        below = pos[:, 1] < WATER_PLANE
        if not (texture in BEACH or (below.sum() >= 20 and col[below, :3].mean() < 0.9)):
            continue
        for j, fs in enumerate(mesh.face_sets):
            idx = np.asarray(fs.indices, dtype="<u2")
            key = f"{fnv1a64(idx.tobytes()):016x}"
            if key in TAKEN:
                print("in another table, left out:", key, model, "mesh", i)
                continue
            lines.append(f"{key} {len(idx)} m13_02_00_00/{model}/mesh{i}/lod{j} {texture}")
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(len(lines) - 1, "face sets written to", OUT)
