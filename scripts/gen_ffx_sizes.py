"""Generate assets/ffx/ffx_sizes.tsv: the flame spread of each effect, for the size rule of the effect lights (ffx_lights sized_reach).

The spread (and the lift, how high the flame's centre stands over the effect's origin) is what the proxy measures from the sprites an effect draws (the light-weighted spread of its additive sprites, metres).
The lookdev host writes that per capture into rtx_comp\\ffx_drawn.tsv (live option proxy.Lights.EffectDrawDump). This script takes
the largest value per effect over a folder of such dumps, one per capture, as the game itself keeps the largest it has seen
(rtx_comp\\ffx_sizes_learned.tsv). Captures must be from a proxy that records the sprite owners (2026-11-11 or later).

Usage: python scripts/gen_ffx_sizes.py <folder with *.tsv dumps> [--out assets/ffx/ffx_sizes.tsv]
"""
import argparse
import csv
import glob
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ap = argparse.ArgumentParser()
ap.add_argument("dumps")
ap.add_argument("--out", default=os.path.join(HERE, "..", "assets", "ffx", "ffx_sizes.tsv"))
args = ap.parse_args()

def warm(r, g, b):
    # ffx_lights.cpp warm(): the lights the size rule applies to.
    return r > 0 and r >= g >= b and r >= 1.6 * b


# Fire lights only: effects with a warm row in the effect light table, and the top effects of the game's own warm effect lights
# seen in the dumps. The rule would not use any other row, and a row is a statement that the effect was looked at.
fire = set()
for line in open(os.path.join(HERE, "..", "assets", "ffx", "ffx_lights.tsv"), encoding="utf-8"):
    f = line.rstrip("\n").split("\t")
    if line.startswith("#") or len(f) < 4:
        continue
    if warm(float(f[1]), float(f[2]), float(f[3])):
        fire.add(int(f[0]))
best = {}
for path in sorted(glob.glob(os.path.join(args.dumps, "*.tsv"))):
    for row in csv.DictReader(open(path, encoding="utf-8"), delimiter="\t"):
        if row["kind"] == "game light" and warm(float(row["light r"]), float(row["light g"]), float(row["light b"])):
            fire.add(int(row["top id"]) or int(row["ffx id"]))
for path in sorted(glob.glob(os.path.join(args.dumps, "*.tsv"))):
    for row in csv.DictReader(open(path, encoding="utf-8"), delimiter="\t"):
        if row["kind"] == "game light" or not row.get("spread m") or int(row["ffx id"]) not in fire:
            continue
        # A handful of sprites says little about a flame's size (the game needs 4 in a frame too).
        if int(row["sprites"]) < 4:
            continue
        effect, spread = int(row["ffx id"]), float(row["spread m"])
        if spread > best.get(effect, (0.0, 0.0, ""))[0]:
            best[effect] = (spread, float(row.get("lift m") or 0.0), os.path.basename(path)[:-4])
with open(args.out, "w", encoding="utf-8", newline="\n") as f:
    f.write("# FFX id <TAB> flame spread in metres <TAB> the flame centre's height over the effect's origin, metres <TAB> the capture "
            "it was measured in. Generated by scripts/gen_ffx_sizes.py.\n")
    for effect in sorted(best):
        f.write(f"{effect}\t{best[effect][0]:.3f}\t{best[effect][1]:.3f}\t{best[effect][2]}\n")
print(f"{len(best)} effects -> {os.path.abspath(args.out)}")
