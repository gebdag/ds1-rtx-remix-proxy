		enum class how : uint8_t
		{
			data_operand,  // sig matches code embedding the address (+adj); the DWORD at match + off, minus adj
			code,          // sig anchored at the address: match + off
			rtti_vtable,   // sig = RTTI class name; adj = its COL offset; off = slot offset in the vtable
			call_to,       // like code, but the sig occurs more than once: the match whose call at +off goes to `from`
			pointer_at,    // the DWORD stored at `from` + off
			offset_from,   // `from` + off: a neighbour of an entry found with two signatures
		};

