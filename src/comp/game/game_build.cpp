		// ---- image -------------------------------------------------------------------------

		struct section
		{
			DWORD va = 0;    // in va_base space
			DWORD size = 0;  // VirtualSize
		};

		struct image_info
		{
			image_view view{};
			DWORD timestamp = 0;
			section text, rdata, data;

			const uint8_t* ptr(DWORD va) const { return view.base + (va - view.va_base); }
			static bool in(const section& s, DWORD va, DWORD n = 1)
			{
				return s.size && va >= s.va && va - s.va <= s.size && s.size - (va - s.va) >= n;
			}
			DWORD dword(DWORD va) const
			{
				DWORD v;
				std::memcpy(&v, ptr(va), 4);
				return v;
			}
		};

		bool read_headers(const image_view& v, image_info& out)
		{
			out.view = v;
			if (!v.base || v.size < 0x400) return false;
			const auto* dos = reinterpret_cast<const IMAGE_DOS_HEADER*>(v.base);
			if (dos->e_magic != IMAGE_DOS_SIGNATURE || dos->e_lfanew <= 0 || static_cast<DWORD>(dos->e_lfanew) > v.size - 0x200)
				return false;
			const auto* nt = reinterpret_cast<const IMAGE_NT_HEADERS32*>(v.base + dos->e_lfanew);
			if (nt->Signature != IMAGE_NT_SIGNATURE) return false;
			out.timestamp = nt->FileHeader.TimeDateStamp;
			const auto* sec = IMAGE_FIRST_SECTION(nt);
			const size_t table_end = reinterpret_cast<const uint8_t*>(sec) - v.base
				+ static_cast<size_t>(nt->FileHeader.NumberOfSections) * sizeof(IMAGE_SECTION_HEADER);
			if (table_end > v.size) return false;
			for (WORD i = 0; i < nt->FileHeader.NumberOfSections; ++i)
			{
				char name[9] = {};
				std::memcpy(name, sec[i].Name, 8);
				const section s{ v.va_base + sec[i].VirtualAddress, sec[i].Misc.VirtualSize };
				if (sec[i].VirtualAddress > v.size || s.size > v.size - sec[i].VirtualAddress) continue;
				if (!std::strcmp(name, ".text")) out.text = s;
				else if (!std::strcmp(name, ".rdata")) out.rdata = s;
				else if (!std::strcmp(name, ".data")) out.data = s;
			}
			return out.text.size && out.rdata.size && out.data.size;
		}

		// ---- signatures --------------------------------------------------------------------

		struct pattern
		{
			std::vector<uint8_t> bytes;
			std::vector<uint8_t> mask; // 1 = must match
		};

		pattern parse(const char* sig)
		{
			pattern p;
			auto nib = [](char c) -> int
			{
				if (c >= '0' && c <= '9') return c - '0';
				if (c >= 'A' && c <= 'F') return c - 'A' + 10;
				if (c >= 'a' && c <= 'f') return c - 'a' + 10;
				return -1;
			};
			for (const char* s = sig; *s;)
			{
				if (*s == ' ') { ++s; continue; }
				if (s[0] == '?')
				{
					p.bytes.push_back(0);
					p.mask.push_back(0);
					s += s[1] == '?' ? 2 : 1;
					continue;
				}
				const int hi = nib(s[0]), lo = s[1] ? nib(s[1]) : -1;
				if (hi < 0 || lo < 0) return {}; // malformed: never matches
				p.bytes.push_back(static_cast<uint8_t>(hi << 4 | lo));
				p.mask.push_back(1);
				s += 2;
			}
			return p;
		}

		bool matches_at(const image_info& img, const pattern& p, DWORD va)
		{
			if (p.bytes.empty() || !image_info::in(img.text, va, static_cast<DWORD>(p.bytes.size())))
				return false;
			const uint8_t* q = img.ptr(va);
			for (size_t i = 0; i < p.bytes.size(); ++i)
				if (p.mask[i] && q[i] != p.bytes[i]) return false;
			return true;
		}

		// Matches in .text (start VAs), up to `limit`.
		int scan(const image_info& img, const pattern& p, DWORD* hits, int limit)
		{
			const size_t n = p.bytes.size();
			if (!n || !p.mask[0] || img.text.size < n) return 0; // signatures start on a concrete byte
			const uint8_t* begin = img.ptr(img.text.va);
			const uint8_t* end = begin + img.text.size - n + 1;
			int count = 0;
			for (const uint8_t* q = begin; q < end && count < limit; ++q)
			{
				q = static_cast<const uint8_t*>(std::memchr(q, p.bytes[0], static_cast<size_t>(end - q)));
				if (!q) break;
				size_t i = 1;
				while (i < n && (!p.mask[i] || q[i] == p.bytes[i])) ++i;
				if (i == n) hits[count++] = img.text.va + static_cast<DWORD>(q - begin);
			}
			return count;
		}

		DWORD call_target(const image_info& img, DWORD va)
		{
			if (!image_info::in(img.text, va, 5) || *img.ptr(va) != 0xE8) return 0;
			return va + 5 + img.dword(va + 1);
		}

		// RTTI: TypeDescriptor (name at +8) -> CompleteObjectLocator in .rdata {0, offset, cdOffset,
		// pTypeDescriptor} -> the .rdata slot pointing at the COL is vtable[-1]. 0 unless exactly one.
		DWORD rtti_vtable(const image_info& img, const char* mangled, DWORD col_offset)
		{
			const DWORD len = static_cast<DWORD>(std::strlen(mangled)) + 1; // with the terminator
			DWORD found = 0;
			int count = 0;
			for (const section* s : { &img.data, &img.rdata })
			{
				if (s->size < len + 8) continue;
				const uint8_t* b = img.ptr(s->va);
				for (DWORD i = 8; i + len <= s->size; ++i)
				{
					if (b[i] != static_cast<uint8_t>(mangled[0]) || std::memcmp(b + i, mangled, len) != 0)
						continue;
					const DWORD td = s->va + i - 8;
					for (DWORD k = 12; k + 4 <= img.rdata.size; k += 4)
					{
						if (img.dword(img.rdata.va + k) != td) continue;
						const DWORD col = img.rdata.va + k - 12;
						if (img.dword(col) != 0 || img.dword(col + 4) != col_offset) continue;
						for (DWORD m = 0; m + 4 <= img.rdata.size; m += 4)
						{
							if (img.dword(img.rdata.va + m) != col) continue;
							found = img.rdata.va + m + 4;
							++count;
						}
					}
				}
			}
			return count == 1 ? found : 0;
		}

		// The one match of `sig` in .text, plus `off`; 0 when it matches never or more than once.
		DWORD unique_match(const image_info& img, const char* sig, int off)
		{
			const pattern p = parse(sig);
			DWORD hits[2];
			return scan(img, p, hits, 2) == 1 ? hits[0] + off : 0;
		}

		int count_dword_in_text(const image_info& img, DWORD value)
		{
			int count = 0;
			const uint8_t* b = img.ptr(img.text.va);
			for (DWORD i = 0; i + 4 <= img.text.size; ++i)
			{
				if (b[i] != static_cast<uint8_t>(value)) continue;
				DWORD v;
				std::memcpy(&v, b + i, 4);
				if (v == value) ++count;
			}
			return count;
		}

		// `done` holds what earlier entries resolved to (call_to / pointer_at go through one).
		DWORD resolved_from(const entry& e, const resolved* done, int n)
		{
			for (int i = 0; i < n; ++i)
				if (done[i].current_va == e.from) return done[i].address;
			return 0;
		}

		DWORD resolve_by_lookup(const image_info& img, const entry& e, const resolved* done, int n)
		{
			switch (e.method)
			{
			case how::rtti_vtable:
			{
				const DWORD vt = rtti_vtable(img, e.sig, static_cast<DWORD>(e.adj));
				const DWORD a = vt ? vt + e.off : 0;
				return image_info::in(img.rdata, a, 4) ? a : 0;
			}
			case how::pointer_at:
			{
				const DWORD from = resolved_from(e, done, n);
				if (!from || !(image_info::in(img.rdata, from + e.off, 4) || image_info::in(img.data, from + e.off, 4)))
					return 0;
				const DWORD a = img.dword(from + e.off);
				return image_info::in(img.text, a) ? a : 0;
			}
			case how::offset_from:
			{
				const DWORD from = resolved_from(e, done, n);
				const DWORD a = from ? from + static_cast<DWORD>(e.off) : 0;
				if (!a || !(image_info::in(img.data, a) || image_info::in(img.rdata, a))) return 0;
				// Code embeds it about as often as in the known builds (allowing a quarter fewer).
				if (e.refs && count_dword_in_text(img, a) < e.refs - e.refs / 4) return 0;
				return a;
			}
			case how::call_to:
			{
				const DWORD target = resolved_from(e, done, n);
				if (!target) return 0;
				const pattern p = parse(e.sig);
				constexpr int kMaxHits = 8;
				DWORD hits[kMaxHits];
				const int count = scan(img, p, hits, kMaxHits);
				if (count >= kMaxHits) return 0; // more matches than were looked at
				DWORD found = 0;
				int calls = 0;
				for (int i = 0; i < count; ++i)
					if (call_target(img, hits[i] + e.off) == target) { found = hits[i] + e.off; ++calls; }
				return calls == 1 ? found : 0;
			}
			case how::code:
			{
				// Both signatures, where there are two, must find the same address.
				const DWORD a = unique_match(img, e.sig, e.off);
				if (!a || !image_info::in(img.text, a)) return 0;
				if (*e.sig2 && unique_match(img, e.sig2, e.off2) != a) return 0;
				return a;
			}
			case how::data_operand:
			{
				const DWORD m = unique_match(img, e.sig, e.off);
				if (!m) return 0;
				const DWORD a = img.dword(m) - static_cast<DWORD>(e.adj);
				if (!image_info::in(img.data, a) && !image_info::in(img.rdata, a)) return 0;
				if (*e.sig2)
				{
					const DWORD m2 = unique_match(img, e.sig2, e.off2);
					if (!m2 || img.dword(m2) - static_cast<DWORD>(e.adj) != a) return 0;
				}
				// Code embeds it about as often as in the known builds (allowing a quarter fewer).
				if (e.refs && count_dword_in_text(img, a + static_cast<DWORD>(e.adj)) < e.refs - e.refs / 4) return 0;
				return a;
			}
			}
			return 0;
		}

		// A table address for code is used only where its signature still matches (a patched or
		// different exe then turns that feature off instead of hooking the wrong bytes).
		bool table_code_ok(const image_info& img, const entry& e, DWORD a, const resolved* done, int n)
		{
			if (e.method == how::code)
				return matches_at(img, parse(e.sig), a - e.off);
			if (e.method == how::call_to)
				return matches_at(img, parse(e.sig), a - e.off) && call_target(img, a) == resolved_from(e, done, n);
			return true;
		}

